// Regenerates jdk_types.tsv: the class hierarchy of the JDK and Groovy types
// groovyrs names, as the JVM reports it.
//
//   JAVA_HOME=... groovy src/host/meta/gen_jdk_types.groovy > src/host/meta/jdk_types.tsv
//
// One line per type: qualified name, `I` for an interface or `C` for a class,
// the direct superclass ('-' for an interface and `Object`), and every
// supertype — superclasses and interfaces, transitively — comma-separated in
// a breadth-first walk from the type.
def types = [
    // java.lang
    Object, String, CharSequence, Comparable, Number, Integer, Long, Short, Byte,
    Double, Float, Boolean, Character, StringBuilder, StringBuffer, Appendable,
    Iterable, Runnable, AutoCloseable, Cloneable, Math, System, Thread, Runtime,
    Throwable, Exception, RuntimeException, Error, Enum, Record, Class,
    // java.io
    Serializable, Closeable, File, Writer, Reader, StringWriter, StringReader,
    // java.math
    BigDecimal, BigInteger, java.math.RoundingMode, java.math.MathContext,
    // java.util
    Collection, List, Set, SortedSet, NavigableSet, Queue, Deque, Map, SortedMap,
    NavigableMap, Map.Entry, RandomAccess, Iterator, ListIterator, Comparator,
    AbstractCollection, AbstractList, AbstractSequentialList, AbstractSet,
    AbstractMap, AbstractQueue, ArrayList, LinkedList, Vector, Stack, ArrayDeque,
    PriorityQueue, HashSet, LinkedHashSet, TreeSet, HashMap, LinkedHashMap,
    TreeMap, Collections, Arrays, Objects, Optional, Random, UUID, Date,
    Calendar, GregorianCalendar, TimeZone, java.util.concurrent.Callable,
    java.util.regex.Pattern, java.util.regex.Matcher,
    java.util.function.Function, java.util.function.BiFunction,
    java.util.function.Supplier, java.util.function.Consumer,
    java.util.function.Predicate,
    // groovy
    Closure, GString, GroovyObject, Writable, Range, IntRange, ObjectRange,
    Expando, Tuple, Tuple2, groovy.lang.GroovyCallable, Script,
]
println "# generated by gen_jdk_types.groovy on Groovy ${GroovySystem.version}, JVM ${System.getProperty('java.version')}"
types.each { Class c ->
    def seen = new LinkedHashSet<Class>()
    def queue = [c]
    while (queue) {
        def cur = queue.remove(0)
        def next = ([cur.superclass] + (cur.interfaces as List)).findAll { it != null }
        next.each { if (seen.add(it)) queue << it }
    }
    println([
        c.name,
        c.isInterface() ? 'I' : 'C',
        c.superclass?.name ?: '-',
        seen*.name.join(',') ?: '-',
    ].join('\t'))
}
