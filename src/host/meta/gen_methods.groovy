// Regenerates methods.tsv: what Apache Groovy's `respondsTo(name)` and
// `hasProperty(name)` answer for the JDK classes groovyrs models, in Groovy's
// own order.
//
//   JAVA_HOME=... groovy src/host/meta/gen_methods.groovy > src/host/meta/methods.tsv
//
// A method line (`M`): receiver class, name, static flag, declaring class,
// return type, parameter types (comma-separated), MetaMethod class, and the
// `toString()` of a reflected (`CachedMethod`) one ('-' otherwise: that
// rendering carries an identity hash).
// A property line (`P`): receiver class, name, type, MetaProperty class.
// A cached-class line (`C`): a type name and the `CachedClass` class Groovy
// answers for it in `parameterTypes`.
def samples = [
    'abc', "a${1}", 1, 1L, 1.5d, 1.5f, 1.5G, 1G, true, 'c' as char,
    [1], new LinkedList([1]), [a: 1], new HashMap(), new TreeMap(),
    [1] as Set, new HashSet(), new TreeSet(), new Object(), 1..2,
    new Expando(),
]
def cached = [:] as TreeMap
println "# generated by gen_methods.groovy on Groovy ${GroovySystem.version}, JVM ${System.getProperty('java.version')}"
samples.each { v ->
    def mc = v.metaClass
    def owner = v.getClass().name
    def names = ((mc.methods + mc.metaMethods)*.name as TreeSet)
    names.each { name ->
        v.respondsTo(name).each { m ->
            (m.parameterTypes.toList() + [m.declaringClass]).each { c -> cached[c.name] = c.getClass().name }
            def text = m instanceof org.codehaus.groovy.reflection.CachedMethod ? m.toString() : '-'
            println([
                'M',
                owner,
                name,
                m.isStatic() ? 1 : 0,
                m.declaringClass.name,
                m.returnType.name,
                m.nativeParameterTypes*.name.join(','),
                m.getClass().name,
                text,
            ].join('\t'))
        }
    }
    mc.properties.each { p ->
        println(['P', owner, p.name, p.type.name, p.getClass().name].join('\t'))
    }
}
cached.each { k, v -> println(['C', k, v].join('\t')) }
// What a script class's own metaclass adds for every instance: the
// `GroovyObject` methods, filed under that interface.
class GenProbe {}
def probe = new GenProbe()
(((probe.metaClass.methods + probe.metaClass.metaMethods)*.name + GroovyObject.methods*.name) as TreeSet).each { name ->
    probe.respondsTo(name).findAll { it.declaringClass.name == 'groovy.lang.GroovyObject' }.each { m ->
        println(['M', 'groovy.lang.GroovyObject', name, m.isStatic() ? 1 : 0, m.declaringClass.name,
                 m.returnType.name, m.nativeParameterTypes*.name.join(','), m.getClass().name,
                 m instanceof org.codehaus.groovy.reflection.CachedMethod ? m.toString() : '-'].join('\t'))
    }
}
