// Regenerates zone_strings.tsv: the JDK's `DateFormatSymbols.getZoneStrings()`
// for Locale.US, in the JDK's own order — the table `SimpleDateFormat` walks,
// first match winning, to parse a zone name (`z`).
//
//   JAVA_HOME=... groovy src/host/meta/gen_zone_strings.groovy > src/host/meta/zone_strings.tsv
//
// One line per zone, tab-separated: id, long standard name, short standard
// name, long daylight name, short daylight name.
println "# generated by gen_zone_strings.groovy on Groovy ${GroovySystem.version}, JVM ${System.getProperty('java.version')}"
java.text.DateFormatSymbols.getInstance(Locale.US).zoneStrings.each { row ->
    println row.take(5).join('\t')
}
