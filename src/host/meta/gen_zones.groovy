// Regenerates zones.tsv: for every zone id the JDK knows, the short names
// (`z` in a date pattern) it gives standard and daylight time, the explicit
// CLDR metazone daylight offset `SimpleDateFormat` tests a zone's offset
// against when one exists, and the JDK's standard-offset history.
//
//   JAVA_HOME=... JAVA_OPTS="--add-opens java.base/java.time.zone=ALL-UNNAMED \
//       --add-exports java.base/sun.util.locale.provider=ALL-UNNAMED" \
//       groovy src/host/meta/gen_zones.groovy > src/host/meta/zones.tsv
//
// One line per id, tab-separated: id, standard short name, daylight short
// name, explicit daylight offset (`-` for none), the first standard offset in
// seconds, then one `epochSecond:offset` per standard-offset transition. The
// standard offsets are the JDK's own (`ZoneRules.standardTransitions`), which
// it compiles from the tz source with negative daylight saving folded into the
// standard offset of each zone line that uses it; whether an instant is
// daylight time in `java.util.TimeZone` is whether its offset differs from
// that standard offset.
import java.time.zone.ZoneRules

def transitions = ZoneRules.getDeclaredField('standardTransitions')
def offsets = ZoneRules.getDeclaredField('standardOffsets')
transitions.accessible = true
offsets.accessible = true
def explicitDst = Class.forName('sun.util.locale.provider.TimeZoneNameUtility')
        .getMethod('explicitDstOffset', String)
println "# generated by gen_zones.groovy on Groovy ${GroovySystem.version}, JVM ${System.getProperty('java.version')}"
TimeZone.availableIDs.sort().each { id ->
    def z = TimeZone.getTimeZone(id)
    def rules = z.toZoneId().rules
    long[] at = transitions.get(rules)
    def std = offsets.get(rules)
    def row = [
        id,
        z.getDisplayName(false, TimeZone.SHORT, Locale.US),
        z.getDisplayName(true, TimeZone.SHORT, Locale.US),
        explicitDst.invoke(null, id) ?: '-',
        std[0].totalSeconds,
    ]
    at.eachWithIndex { t, i -> row << "${t}:${std[i + 1].totalSeconds}" }
    println row.join('\t')
}
