// Regenerates zones.tsv: the short names (`z` in a date pattern) the JDK
// gives every zone id it knows, for standard and daylight time.
//
//   JAVA_HOME=... groovy src/host/meta/gen_zones.groovy > src/host/meta/zones.tsv
//
// One line per id: id, standard short name, daylight short name.
println "# generated by gen_zones.groovy on Groovy ${GroovySystem.version}, JVM ${System.getProperty('java.version')}"
TimeZone.availableIDs.sort().each { id ->
    def z = TimeZone.getTimeZone(id)
    println([id, z.getDisplayName(false, TimeZone.SHORT, Locale.US), z.getDisplayName(true, TimeZone.SHORT, Locale.US)].join('\t'))
}
